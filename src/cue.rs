//! The mute switch's audio cue: a short two-tone figure on the system's default output device.
//!
//! The WAV is generated here rather than shipped as an asset, and playback goes through `PlaySound`,
//! which uses the default endpoint and never touches a line's bus. Muting falls, unmuting rises, so the
//! direction says which way the switch went. `LazyLock` keeps the bytes alive for `SND_ASYNC`.

use std::sync::LazyLock;

use windows::core::PCWSTR;
use windows::Win32::Media::Audio::{PlaySoundW, SND_ASYNC, SND_MEMORY, SND_NODEFAULT};

const RATE: u32 = 48_000;
/// Quiet enough to sit under speech.
const AMPLITUDE: f32 = 0.12;
/// Every note starts and ends at zero, so the cue cannot click.
const FADE_SECONDS: f64 = 0.004;

static MUTE: LazyLock<Vec<u8>> = LazyLock::new(|| wav(&[(880.0, 0.055), (587.33, 0.075)]));
static UNMUTE: LazyLock<Vec<u8>> = LazyLock::new(|| wav(&[(587.33, 0.055), (880.0, 0.075)]));

pub fn muted() {
    play(&MUTE);
}

pub fn unmuted() {
    play(&UNMUTE);
}

#[cfg(not(test))]
fn play(wav: &'static [u8]) {
    let played = unsafe {
        PlaySoundW(
            PCWSTR(wav.as_ptr() as *const u16),
            None,
            SND_ASYNC | SND_MEMORY | SND_NODEFAULT,
        )
    };
    if !played.as_bool() {
        crate::log::line("cue: the default output refused the sound");
    }
}

/// Tests must not make noise on the machine running them; the generated bytes are what they check.
#[cfg(test)]
fn play(_wav: &'static [u8]) {}

fn wav(notes: &[(f64, f64)]) -> Vec<u8> {
    let frames: usize = notes
        .iter()
        .map(|(_, seconds)| (seconds * f64::from(RATE)) as usize)
        .sum();
    let data_len = frames * 2;
    let mut out = Vec::with_capacity(44 + data_len);
    out.extend_from_slice(b"RIFF");
    out.extend_from_slice(&((36 + data_len) as u32).to_le_bytes());
    out.extend_from_slice(b"WAVEfmt ");
    out.extend_from_slice(&16u32.to_le_bytes());
    out.extend_from_slice(&1u16.to_le_bytes());
    out.extend_from_slice(&1u16.to_le_bytes());
    out.extend_from_slice(&RATE.to_le_bytes());
    out.extend_from_slice(&(RATE * 2).to_le_bytes());
    out.extend_from_slice(&2u16.to_le_bytes());
    out.extend_from_slice(&16u16.to_le_bytes());
    out.extend_from_slice(b"data");
    out.extend_from_slice(&(data_len as u32).to_le_bytes());

    let fade = (FADE_SECONDS * f64::from(RATE)) as usize;
    for (hz, seconds) in notes {
        let frames = (seconds * f64::from(RATE)) as usize;
        for frame in 0..frames {
            let time = frame as f64 / f64::from(RATE);
            let edge = frame.min(frames - 1 - frame);
            let gain = if edge < fade {
                edge as f32 / fade as f32
            } else {
                1.0
            };
            let sample = (std::f64::consts::TAU * hz * time).sin() as f32 * AMPLITUDE * gain;
            let value = (sample * f32::from(i16::MAX)) as i16;
            out.extend_from_slice(&value.to_le_bytes());
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn samples(wav: &[u8]) -> Vec<i16> {
        assert_eq!(&wav[0..4], b"RIFF");
        assert_eq!(&wav[8..12], b"WAVE");
        assert_eq!(&wav[12..16], b"fmt ");
        assert_eq!(&wav[36..40], b"data");
        assert_eq!(u16::from_le_bytes([wav[22], wav[23]]), 1, "mono");
        assert_eq!(
            u32::from_le_bytes([wav[24], wav[25], wav[26], wav[27]]),
            RATE
        );
        assert_eq!(u16::from_le_bytes([wav[34], wav[35]]), 16, "16-bit pcm");
        let declared = u32::from_le_bytes([wav[40], wav[41], wav[42], wav[43]]) as usize;
        assert_eq!(declared, wav.len() - 44, "data chunk matches the file");
        wav[44..]
            .chunks_exact(2)
            .map(|pair| i16::from_le_bytes([pair[0], pair[1]]))
            .collect()
    }

    #[test]
    fn each_cue_is_a_valid_quiet_wav_that_opens_and_closes_silently() {
        for cue in [&*MUTE, &*UNMUTE] {
            let pcm = samples(cue);
            assert_eq!(pcm.len(), (0.130 * f64::from(RATE)) as usize, "130 ms");
            assert_eq!(pcm[0], 0, "no click on entry");
            assert_eq!(*pcm.last().unwrap(), 0, "no click on exit");
            let peak = pcm.iter().map(|s| s.unsigned_abs()).max().unwrap_or(0);
            assert!(peak > 2000, "audible: {peak}");
            assert!(peak <= (AMPLITUDE * f32::from(i16::MAX)) as u16 + 1, "not loud");
        }
        assert_ne!(&MUTE[44..], &UNMUTE[44..], "the two directions differ");
    }

    /// A 1 kHz note for 20 ms must cross zero about twenty times; this is what proves the generator is
    /// writing the pitch it was handed rather than a header with plausible silence.
    #[test]
    fn a_generated_note_has_the_frequency_it_was_given() {
        let pcm = samples(&wav(&[(1000.0, 0.020)]));
        let rising = pcm.windows(2).filter(|w| w[0] <= 0 && w[1] > 0).count();
        assert!((18..=22).contains(&rising), "rising crossings: {rising}");
    }
}
